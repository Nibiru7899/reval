"""Generate the committed examples/motor_thermal/subjects.yaml (id -> subject mapping, via subjects_file)."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT.parents[1] / "src"))

import pandas as pd  # noqa: E402
import yaml  # noqa: E402
from motor.cycles import make_library  # noqa: E402
from motor.splits import load_splits  # noqa: E402

SEED = 0


def main() -> None:
    df = pd.read_parquet(ROOT / "data" / "processed" / "measures.parquet")
    splits = load_splits(ROOT / "splits.yaml")
    lib = make_library(SEED, splits, data=df)
    subjects = {s["id"]: {k: v for k, v in s.items() if k != "id"} for s in lib}
    subjects["SHAFT-1"] = {"kind": "design", "params": {}}  # target of the analytic shaft claim
    header = (
        "# Generated by scripts/make_subjects.py (seed 0). Do not edit by hand.\n"
        "# DC-P*: parametric cycles, ~20 percent deliberately outside the train envelope.\n"
        "# DC-R*: recorded segments of test profiles only.\n"
    )
    body = yaml.safe_dump(subjects, sort_keys=False, width=110, default_flow_style=None)
    (ROOT / "subjects.yaml").write_text(header + body, encoding="utf-8")
    print(f"wrote {len(subjects)} subjects")


if __name__ == "__main__":
    main()
