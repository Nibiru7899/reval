"""Estimate LPTN sensitivities and write params/tolerances.yaml (committed; read by lptn_sim).

Run: .venv/Scripts/python examples/motor_thermal/scripts/sensitivities.py [--per-class 3,3,2]
Deterministic: no randomness; cycles are picked by id order from subjects.yaml.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import joblib
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT.parents[1] / "src"))

from motor import cycles as cyc  # noqa: E402
from motor import lptn  # noqa: E402
from motor.sensitivities import FLOW_FIELD, estimate_tolerances  # noqa: E402

KAPPA = 1.5
FLOW_GRID = [0.7, 0.85, 1.0, 1.15, 1.3]  # = A-flow-sens bounds
LEAF_REL = [0.8, 0.9, 1.0, 1.1, 1.2]  # leaf grid as multiples of the calibrated value
LEAF_GROUPS = ("R", "C")


def assumption_id(field: str) -> str:
    """One sensitivity assumption per tolerance (declared in reval.yaml)."""
    return "A-flow-sens" if field == FLOW_FIELD else "A-sens-" + field.split("#/")[1].replace("/", "-")


def pick_cycles(per_class: dict[str, int]) -> list[tuple[str, dict[str, Any]]]:
    """First in-domain duty cycles by id order, per length class."""
    subjects = yaml.safe_load((ROOT / "subjects.yaml").read_text(encoding="utf-8"))
    df = pd.read_parquet(ROOT / "data" / "processed" / "measures.parquet")
    drive_map = joblib.load(ROOT / "models" / "drive_map.joblib")
    chosen: dict[str, list[tuple[str, dict[str, Any]]]] = {k: [] for k in per_class}
    for sid in sorted(subjects):
        s = subjects[sid]
        if s.get("kind") != "duty_cycle":
            continue
        p = s["params"]
        if s["generator"] == "motor.cycles:blocks":
            cycle, theta0 = cyc.blocks(p), None
        else:
            cycle = cyc.recorded(int(p["profile_id"]), float(p["start_s"]), float(p["duration_s"]), df)
            seg = cyc._segment(int(p["profile_id"]), float(p["start_s"]), float(p["duration_s"]), df)
            theta0 = {n: float(seg.iloc[0][n]) for n in lptn.NODES}
        cls = cyc.length_class(len(cycle) * cyc.DT_S)
        if len(chosen[cls]) >= per_class[cls]:
            continue
        torque, speed = cycle["torque"].to_numpy(), cycle["motor_speed"].to_numpy()
        if not drive_map.domain_report(torque, speed).inside:
            continue  # out-of-domain cycles are point-only in lptn_sim, so tolerances never apply to them
        inputs = drive_map.to_inputs(torque, speed, cycle["coolant"].to_numpy(), cycle["ambient"].to_numpy())
        chosen[cls].append((sid, {"inputs": inputs, "theta0": theta0}))
    return [c for cls in per_class for c in chosen[cls]]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-class", default="3,3,2", help="short,medium,long cycle counts")
    args = ap.parse_args()
    counts = [int(v) for v in args.per_class.split(",")]
    picked = pick_cycles(dict(zip(("short", "medium", "long"), counts, strict=True)))
    cycles = [c for _, c in picked]
    params = lptn.load_params(ROOT / "params" / "lptn.yaml")
    flat = lptn._to_flat(params)

    jobs: list[tuple[str, list[float]]] = [(FLOW_FIELD, FLOW_GRID)]
    for key, value in flat.items():
        if key.split("/")[1] in LEAF_GROUPS:
            jobs.append((f"lptn#{key}", [value * r for r in LEAF_REL]))

    entries = []
    for field, grid in jobs:
        (tol,) = estimate_tolerances(
            params, field, grid, cycles, assumption_id=assumption_id(field), kappa=KAPPA
        )
        d = tol.model_dump(mode="json")
        d["valid_range"] = [float(v) for v in tol.valid_range]
        entries.append(d)
        print(f"{field}: {tol.sensitivity:.6g} K per {tol.input_unit}")
    header = (
        "# Generated by scripts/sensitivities.py. Do not hand-edit.\n"
        f"# Cycles: {', '.join(sid for sid, _ in picked)}.\n"
        "# sensitivity is the RAW max |d peak / d field| in K per input unit; kappa lives in safety_factor\n"
        "# and is applied once, at inflation time. Empirical, not a proof.\n"
    )
    text = header + yaml.safe_dump({"tolerances": entries}, sort_keys=False, width=120)
    (ROOT / "params" / "tolerances.yaml").write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
