"""Render the M4 demo summary (markdown) from the demo's JSON outputs; nothing here is typed by hand."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def _statuses(path: Path) -> dict[str, str]:
    data = json.loads(path.read_text(encoding="utf-8"))
    return {a["claim_id"]: a["status"] for a in data["assessments"]}


def main(argv: list[str] | None = None) -> Path:
    ap = argparse.ArgumentParser()
    for name in ("plan", "before", "after", "transcript", "out"):
        ap.add_argument(f"--{name}", required=True, type=Path)
    a = ap.parse_args(argv)
    plan = json.loads(a.plan.read_text(encoding="utf-8"))
    before, after = _statuses(a.before), _statuses(a.after)
    transcript = a.transcript.read_text(encoding="utf-8", errors="replace")
    ran = re.findall(r"^ran \d+ producer results", transcript, flags=re.M)
    lines = [
        "# 2026-10-28: M4 demo (diff -> plan -> run -> report)",
        "",
        "Generated by `examples/motor_thermal/demo_full.{sh,ps1}` (claims trimmed",
        "to DC-P01, DC-R01, SHAFT-1 in a throwaway copy); every number is read from the demo JSON.",
        "",
        f"- Plan `{plan['id'][:12]}`: planner {plan['planner']}, objective {plan['objective']}, solver "
        f"{plan['solver_status']}, total cost {plan['total_cost']}, {len(plan['runs'])} runs, "
        f"unrestorable {len(plan['unrestorable'])}, deferred {len(plan['deferred'])}.",
        f"- Producer-result lines in transcript: {'; '.join(ran)}",
        "",
        "## Planned runs",
        "",
        "| producer | subject | cost | discharges |",
        "|---|---|---|---|",
    ]
    for r in plan["runs"]:
        lines.append(
            f"| {r['producer_id']} | {r['subject_id']} | {r['cost']} | {', '.join(r['discharges'])} |"
        )
    lines += [
        "",
        "## Claim status after the change",
        "",
        "| claim | before restoration | after `run --plan` |",
        "|---|---|---|",
    ]
    for c in sorted(after):
        lines.append(f"| {c} | {before.get(c, '-')} | {after[c]} |")
    restored = sorted(c for c in after if before.get(c) != "supported" and after[c] == "supported")
    lines += [
        "",
        f"Restored to supported by the plan: {', '.join(restored) if restored else 'none'}.",
        "",
        "Statuses mean supported by recorded evidence against the declared requirement,",
        "not a safety statement.",
        "",
    ]
    a.out.write_text("\n".join(lines), encoding="utf-8")
    return a.out


if __name__ == "__main__":
    main()
